// The mail app closes the composer while onSend is still running. Its unmount
// auto-save then handed the message back as an unsent draft, and the
// "Continue draft" banner flashed after every send.

const DRAFT = {
  to: 'bob@example.com',
  cc: '',
  bcc: '',
  subject: 'Lunch',
  body: '<p>Hello there</p>',
  showCc: false,
  showBcc: false,
  selectedIdentityId: 'id-me',
  subAddressTag: '',
  mode: 'compose' as const,
  draftId: null,
};

function Host({ onSend, onSaveState }: { onSend: () => Promise<void>; onSaveState: () => void }) {
  const [open, setOpen] = useState(true);
  if (!open) return <p>closed</p>;
  return (
    <EmailComposer
      initialData={DRAFT}
      onSaveState={onSaveState}
      onSend={async () => {
        setOpen(false);
        await onSend();
      }}
    />
  );
}

const sendButton = () => screen.getAllByTestId('composer-send')[0] as HTMLButtonElement;

describe('composer closed during send', () => {
  beforeEach(() => {
    toastError.mockClear();
    updateSetting.mockClear();
    editorKeyDown.mockClear();
  });

  it('does not hand the sent message back as a draft', async () => {
    const onSaveState = vi.fn();
    render(<Host onSend={() => new Promise((r) => setTimeout(r, 20))} onSaveState={onSaveState} />);

    // Typed into, so the composer counts as changed when it unmounts.
    fireEvent.change(screen.getByTestId('composer-subject'), { target: { value: 'Lunch on Friday' } });
    fireEvent.click(sendButton());

    await screen.findByText('closed');
    await act(() => new Promise((r) => setTimeout(r, 50)));
    expect(onSaveState).not.toHaveBeenCalled();
  });
});
